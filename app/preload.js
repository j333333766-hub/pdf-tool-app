const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  ready: call('ready'),
  pickPdfs: call('pick-pdfs'),
  pickImage: call('pick-image'),
  pickPdfsImages: call('pick-pdfs-images'),
  pickXlsx: call('pick-xlsx'),
  pickDir: call('pick-dir'),
  savePdf: call('save-pdf'),
  readFile: call('read-file'),
  pageCount: call('page-count'),
  merge: call('merge'),
  parseRanges: call('parse-ranges'),
  split: call('split'),
  sign: call('sign'),
  parsePages: call('parse-pages'),
  rotate: call('rotate'),
  organize: call('organize'),
  stamp: call('stamp'),
  unspread: call('unspread'),
  crop: call('crop'),
  fromJpegs: call('from-jpegs'),
  splitNamed: call('split-named'),
  writeFiles: call('write-files'),
  fileSize: call('file-size'),
  rosterGet: call('roster-get'),
  rosterSet: call('roster-set'),
  rosterSample: call('roster-sample'),
  editOpen: call('edit-open'),
  editPage: call('edit-page'),
  editApply: call('edit-apply'),
  editUndo: call('edit-undo'),
  editSave: call('edit-save'),
  editImageSize: call('edit-image-size'),
  showInFolder: call('show-in-folder'),
  openPath: call('open-path'),
  sigList: call('sig-list'),
  sigSave: call('sig-save'),
  sigDelete: call('sig-delete'),
  ctxStatus: call('ctx-status'),
  ctxSet: call('ctx-set'),
  menu11Status: call('menu11-status'),
  menu11Set: call('menu11-set'),
  hwpConvert: call('hwp-convert'),
  hwpCancel: call('hwp-cancel'),
  pickHwps: call('pick-hwps'),
  onHwpProgress: (cb) => ipcRenderer.on('hwp-progress', (_e, p) => cb(p)),
  // 끌어다 놓은 파일의 실제 경로
  pathOf: (file) => webUtils.getPathForFile(file),
  onOpenFiles: (cb) => ipcRenderer.on('open-files', (_e, data) => cb(data)),
});
